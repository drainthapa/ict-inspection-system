// Regenerates database/schema.sql as the concatenation of all migrations,
// so schema.sql always shows the full, current structure in one file.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '../database');
const files = (await fs.readdir(path.join(root, 'migrations'))).filter((f) => f.endsWith('.sql')).sort();

let out = '-- AUTO-GENERATED by `npm run db:schema` from database/migrations. Do not edit by hand.\n'
  + '-- To change the schema, add a new numbered migration file.\n\n';
for (const f of files) {
  out += `-- >>> ${f}\n${await fs.readFile(path.join(root, 'migrations', f), 'utf8')}\n`;
}
await fs.writeFile(path.join(root, 'schema.sql'), out);
console.log(`schema.sql written from ${files.length} migration(s)`);
